#!/usr/bin/env python3
"""Translate the existing SPIR-V artifacts with shared/web-port's pinned tool."""

import argparse
from pathlib import Path
import subprocess
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("converter", type=Path, help="shared/web-port/tools/shaders.py")
    parser.add_argument("--build-dir", type=Path, default=Path("build/wgsl"))
    parser.add_argument("--check", action="store_true", help="refuse stale committed WGSL")
    args = parser.parse_args()
    source = Path(__file__).resolve().parent
    args.build_dir.mkdir(parents=True, exist_ok=True)
    blocks = ["// Generated by compile_wgsl.py from ShadersCompiledSPV.h; do not edit.\n"]
    for name in ("shader_frag_color", "shader_frag_texture", "shader_vert"):
        output = args.build_dir / f"{name}.inc"
        subprocess.run(
            [
                sys.executable,
                str(args.converter.resolve(strict=True)),
                "convert",
                str(source / "ShadersCompiledSPV.h"),
                str(output),
                "--c-array",
                f"{name}_spirv",
                "--include",
            ],
            check=True,
        )
        blocks.append(f"static const unsigned char {name}_wgsl[] =\n{output.read_text()};\n")
    header = source / "ShadersCompiledWGSL.h"
    generated = "\n".join(blocks)
    if args.check:
        if header.read_text() != generated:
            raise SystemExit("ShadersCompiledWGSL.h differs from translated SPIR-V")
        print("WGSL artifacts: 3 shaders match translated SPIR-V")
    else:
        header.write_text(generated)


if __name__ == "__main__":
    main()
